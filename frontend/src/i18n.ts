export function translateText(text: string, locale: Locale): string {
  if (locale === 'en') return text
  const trimmed = text.trim()
  const leading = text.match(/^\s*/)?.[0] || ''
  const trailing = text.match(/\s*$/)?.[0] || ''
  let translated = arabic[trimmed]
  if (!translated) {
    if (trimmed.startsWith('Good morning, ')) translated = `صباح الخير، ${trimmed.slice('Good morning, '.length)}`
    else if (trimmed.startsWith('Hey, ')) translated = `مرحباً، ${trimmed.slice(5).replace('👋', '').trim()} 👋`
    else translated = trimmed
  }
  return `${leading}${translated}${trailing}`
}
